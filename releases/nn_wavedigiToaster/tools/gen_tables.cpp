// gen_tables.cpp - host tool that writes ../src/toaster_tables.h
//
// The two JFET stages of the Noise Toaster that have no capacitors (the AREG
// output buffer Q9 and the VCA Q7) are memoryless nonlinear resistive
// circuits. A wave digital tree with one nonlinear root and no reactances
// collapses to "solve the node equation for the root voltage", so we solve
// those equations exactly here, offline, with bisection, and tabulate them.
// The card then only interpolates.
//
// Build & run:  g++ -O2 -std=c++17 gen_tables.cpp -o gen_tables && ./gen_tables
// (tools/build_tables.sh does this)

#include <cstdio>
#include <cmath>
#include <cstdint>

#include "../src/jfet.h"

// Solve f(vs) = 0 for a function decreasing in vs on [lo, hi].
template <typename F>
static double bisect(F f, double lo, double hi)
{
	for (int i = 0; i < 80; i++)
	{
		double mid = 0.5 * (lo + hi);
		if (f(mid) > 0) lo = mid; else hi = mid;
	}
	return 0.5 * (lo + hi);
}

int main()
{
	FILE *f = fopen("../src/toaster_tables.h", "w");
	if (!f) { printf("cannot open ../src/toaster_tables.h\n"); return 1; }

	fprintf(f, "// toaster_tables.h - GENERATED by tools/gen_tables.cpp, do not edit.\n");
	fprintf(f, "// All voltages Q16 (65536 = 1 V), absolute (B- = 0 V).\n\n");
	fprintf(f, "#pragma once\n#include <cstdint>\n\n");

	// exp2 table: 2^(i/256), Q30, 257 entries
	fprintf(f, "// 2^(i/256), Q30\n");
	fprintf(f, "static uint32_t exp2Table[257] = {");
	for (int i = 0; i <= 256; i++)
	{
		if (i % 8 == 0) fprintf(f, "\n\t");
		fprintf(f, "%lu,", (unsigned long)llround(std::pow(2.0, i / 256.0) * 1073741824.0));
	}
	fprintf(f, "\n};\n\n");

	// Q9: source follower. Drain = B+ (9 V), source -> R54 (4.7k) -> B-.
	// Gate = C18 voltage (via R52, no gate current).
	const int Q9N = 129;
	const double Q9MAX = 9.6;
	fprintf(f, "// AREG buffer Q9 (2N5457 source follower, R54 = 4k7): ARG = f(V_C18)\n");
	fprintf(f, "// %d points over V_C18 = 0 .. %.2f V\n", Q9N, Q9MAX);
	fprintf(f, "constexpr int Q9_N = %d;\n", Q9N);
	fprintf(f, "constexpr float Q9_VMAX = %.4ff;\n", Q9MAX);
	fprintf(f, "static int32_t q9Table[%d] = {", Q9N);
	for (int i = 0; i < Q9N; i++)
	{
		double vg = Q9MAX * i / (Q9N - 1);
		double vs = bisect([&](double s) { return jfet::id(vg - s, 9.0 - s) - s / 4700.0; }, 0.0, 9.0);
		if (i % 8 == 0) fprintf(f, "\n\t");
		fprintf(f, "%ld,", (long)llround(vs * 65536.0));
	}
	fprintf(f, "\n};\n\n");

	// Q7: VCA. Drain = VCF output (FO), source = X13 loaded by R47 (100k) || R66
	// (100k volume pot) to B-. Gate = ARG * R46/(R41+R46).
	const int VGN = 65, VDN = 65;
	const double VGMAX = 6.4, VDMAX = 8.0;
	const double RL = 1.0 / (1.0 / 100e3 + 1.0 / 100e3);
	fprintf(f, "// VCA Q7 (2N5457, source load R47 || R66 = 50k): V_X13 = f(V_gate, V_FO)\n");
	fprintf(f, "// [gate %d pts 0..%.2f V][drain %d pts 0..%.2f V]\n", VGN, VGMAX, VDN, VDMAX);
	fprintf(f, "constexpr int VCA_GN = %d;\nconstexpr int VCA_DN = %d;\n", VGN, VDN);
	fprintf(f, "constexpr float VCA_GMAX = %.4ff;\nconstexpr float VCA_DMAX = %.4ff;\n", VGMAX, VDMAX);
	fprintf(f, "static int32_t vcaTable[%d][%d] = {", VGN, VDN);
	for (int g = 0; g < VGN; g++)
	{
		double vg = VGMAX * g / (VGN - 1);
		fprintf(f, "\n\t{");
		for (int d = 0; d < VDN; d++)
		{
			double vd = VDMAX * d / (VDN - 1);
			double vs = bisect([&](double s) { return jfet::id(vg - s, vd - s) - s / RL; }, 0.0, vd);
			fprintf(f, "%ld,", (long)llround(vs * 65536.0));
		}
		fprintf(f, "},");
	}
	fprintf(f, "\n};\n");
	fclose(f);
	printf("wrote ../src/toaster_tables.h\n");
	return 0;
}
